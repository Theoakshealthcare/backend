class OpsSeed:
    """Rows the bookings section needs and no API creates: patients, approved caregivers with a fresh location,
    and bookings in each state. Every seeded row is placeholder data."""

    def __init__(self, db: DB, env: Dict[str, str], tag: str):
        self.db, self.tag, self.n = db, tag, 0
        self.fernet = Fernet(env["VITALS_ENCRYPTION_KEY"].split(",")[0].strip().encode())

    def _phone(self) -> str:
        self.n += 1
        return f"+2340000{int(self.tag, 16) % 1000:03d}{self.n:03d}"

    def _user(self, kind: str, name: str) -> str:
        uid = str(uuid.uuid4())
        self.db.run("INSERT INTO users (id, email, phone_number, full_name, hashed_password, user_type, is_active,"
                    " is_verified, created_at, updated_at) VALUES (%s,%s,%s,%s,%s,%s,true,true,now(),now())",
                    (uid, f"{kind}-{uid[:8]}-{self.tag}@example.com", self._phone(), name, hash_password(PLACEHOLDER_PASSWORD), kind))
        return uid

    def patient(self, name: str) -> str:
        uid = self._user("patient", name)
        pid = str(uuid.uuid4())
        (phone, email), = self.db.run("SELECT phone_number, email FROM users WHERE id = %s", (uid,))
        self.db.run("INSERT INTO patients (id, user_id, email, full_name, phone_number, city, state, is_active,"
                    " created_at, updated_at) VALUES (%s,%s,%s,%s,%s,'Lagos','Lagos',true,now(),now())",
                    (pid, uid, email, name, phone))
        return pid

    def caregiver(self, name: str, approved: bool = True, located: bool = True, offset: float = 0.002) -> str:
        uid = self._user("caregiver", name)
        cid = str(uuid.uuid4())
        (phone, email), = self.db.run("SELECT phone_number, email FROM users WHERE id = %s", (uid,))
        self.db.run(
            "INSERT INTO caregivers (id, user_id, email, full_name, phone_number, state, specialization,"
            " years_of_experience, profile_completion_step, identity_verification_status, background_check_status,"
            " profile_status, created_at, updated_at) VALUES (%s,%s,%s,%s,%s,'Lagos','nurse',5,3,%s,'cleared',%s,"
            " now(), now())",
            (cid, uid, email, name, phone, "verified" if approved else "pending",
             "approved" if approved else "under_review"))
        self.db.run("INSERT INTO caregiver_skills (id, caregiver_id, service_type, created_at)"
                    " VALUES (%s,%s,'nurse',now())", (str(uuid.uuid4()), cid))
        if located:
            self.db.run("INSERT INTO caregiver_locations (id, caregiver_id, latitude, longitude, is_active,"
                        " is_available, recorded_at, updated_at) VALUES (%s,%s,%s,%s,true,true,now(),now())",
                        (str(uuid.uuid4()), cid, LAT + offset, LON))
        return cid

    def booking(self, patient_id: str, *, status: str = "PENDING", payment: str = "PAID", hours_ahead: float = 26,
                caregiver_id: Optional[str] = None, channel: str = "app", held: bool = False,
                dispatch_state: Optional[str] = None, dispatch_started_ago_min: Optional[int] = None,
                condition: Optional[str] = "Placeholder condition (plain)", encrypted: Optional[str] = None,
                started: bool = False, lat: float = LAT, lon: float = LON) -> Dict[str, Any]:
        bid, code = str(uuid.uuid4()), uuid.uuid4().hex[:8].upper()
        start = datetime.utcnow() + timedelta(hours=hours_ahead)
        started_at = datetime.utcnow() + timedelta(minutes=-dispatch_started_ago_min) if dispatch_started_ago_min \
            else None
        self.db.run(
            "INSERT INTO bookings (id, booking_code, patient_id, caregiver_id, service_type, assistance_type,"
            " condition, condition_encrypted, duration_hours, scheduled_date, scheduled_end_date, actual_start_time,"
            " patient_address, patient_latitude, patient_longitude, patient_city, patient_state, needs_address_check,"
            " channel, status, payment_status, dispatch_state, dispatch_started_at, total_amount_kobo,"
            " service_fee_kobo, platform_fee_kobo, paystack_reference, booking_for, special_instructions,"
            " refund_required, visit_code_failed_attempts, created_at, updated_at)"
            " VALUES (%s,%s,%s,%s,'nurse','Placeholder assistance',%s,%s,2,%s,%s,%s,"
            " '12 Placeholder Street, Lekki',%s,%s,'Lagos','Lagos',%s,%s,%s,%s,%s,%s,5500000,5000000,500000,%s,"
            " 'myself','Placeholder instructions (gate code 0000)',false,0,now() - interval '40 minutes',now())",
            (bid, code, patient_id, caregiver_id, condition, encrypted and self.fernet.encrypt(encrypted.encode()).decode(),
             start, start + timedelta(hours=2), datetime.utcnow() if started else None, lat, lon, held, channel,
             status, payment, dispatch_state, started_at, f"BKG_{code}_{uuid.uuid4().hex[:8]}"))
        return {"id": bid, "code": code}


def bookings_ops(rec: Recorder, db: DB, env: Dict[str, str], tag: str) -> None:
    """A2: the bookings list, detail, unmatched queue and every action, as the roles that use them."""
    admins = Admins(db, env, tag + "ops")
    seed = OpsSeed(db, env, tag)
    wait_for_new_rate_window()
    rec.quiet = True
    tokens = {}
    for who, role in (("boss", "super_admin"), ("ops", "operations"), ("fin", "finance"),
                      ("clin", "clinical_reviewer")):
        tokens[who] = login_and_verify(rec, admins, who, admins.seed(who, role, f"Placeholder {role}"))["access_token"]
    rec.quiet = False
    boss, ops, fin, clin = tokens["boss"], tokens["ops"], tokens["fin"], tokens["clin"]
    B = f"{ADMIN}/bookings"
    seeded = ("SEEDED: patients, caregivers and bookings are inserted directly (no API creates them without a live "
              "Paystack account). Everything is placeholder data.")

    ada, bola, chi = seed.patient("Ada Okafor"), seed.patient("Bola Adeyemi"), seed.patient("Chidi Eze")
    cg1 = seed.caregiver("Placeholder Nurse One", offset=0.002)
    cg2 = seed.caregiver("Placeholder Nurse Two", offset=0.004)
    cg_far = seed.caregiver("Placeholder Nurse Far", offset=0.3)
    cg_unapproved = seed.caregiver("Placeholder Applicant", approved=False, located=False)
    unmatched = seed.booking(ada, dispatch_state="unmatched", dispatch_started_ago_min=90, hours_ahead=5)
    held = seed.booking(bola, channel="whatsapp", held=True, hours_ahead=30, lat=6.5244, lon=3.3792,
                        condition=None, encrypted="Placeholder condition (typed in the WhatsApp Flow)")
    late = seed.booking(chi, status="ACCEPTED", caregiver_id=cg1, dispatch_state="matched", hours_ahead=-0.5)
    running = seed.booking(ada, status="IN_PROGRESS", caregiver_id=cg2, dispatch_state="matched", hours_ahead=-1,
                           started=True)
    to_cancel = seed.booking(bola, channel="whatsapp", dispatch_state="dispatching", dispatch_started_ago_min=5,
                             hours_ahead=40)
    to_offer = seed.booking(chi, dispatch_state="dispatching", dispatch_started_ago_min=3, hours_ahead=48)
    to_force = seed.booking(ada, dispatch_state="unmatched", dispatch_started_ago_min=60, hours_ahead=50)
    to_reassign = seed.booking(bola, status="ACCEPTED", caregiver_id=cg1, dispatch_state="matched", hours_ahead=28)
    unpaid = seed.booking(chi, payment="PENDING", hours_ahead=60)

    # --- reading ---------------------------------------------------------------------------------------
    rec.call("bookings-list", "GET", B, token=ops, params={"limit": 3},
             note="Operations holds people.pii, so names and phones are in full. " + seeded)
    rec.call("bookings-list-filtered", "GET", B, token=ops, params={
        "status": "pending", "payment_status": "paid", "channel": "whatsapp", "sort": "created_at", "order": "desc"})
    rec.call("bookings-list-search", "GET", B, token=ops, params={"q": "okafor"})
    rec.call("bookings-list-no-show", "GET", B, token=ops, params={"no_show": "true"},
             note="Flagged or suspected no-shows: an accepted visit 15 minutes past its start with no check-in.")
    rec.call("bookings-list-masked", "GET", B, token=fin, params={"limit": 2},
             note="Finance holds bookings.read but not people.pii: names and phones are shortened.")
    rec.call("bookings-list-bad-status", "GET", B, token=ops, expect=422, params={"status": "nonsense"})
    rec.call("bookings-unmatched", "GET", f"{B}/unmatched", token=ops)
    rec.call("bookings-unmatched-held", "GET", f"{B}/unmatched", token=ops, params={"reason": "address_check"})

    rec.call("booking-detail-ops", "GET", f"{B}/{unmatched['id']}", token=ops,
             note="Operations may see the address (bookings.address) but not the condition (clinical.read).")
    rec.call("booking-detail-held-whatsapp", "GET", f"{B}/{held['id']}", token=ops,
             note="A WhatsApp booking held for an address check: the pin is a city-centre placeholder.")
    rec.call("booking-detail-finance", "GET", f"{B}/{unmatched['id']}", token=fin,
             note="Finance: no bookings.address, no people.pii, no clinical.read.")
    rec.call("booking-detail-clinical", "GET", f"{B}/{held['id']}", token=clin,
             note="Clinical Reviewer: the decrypted condition is returned and this read is written to the audit log.")
    rec.call("booking-detail-not-found", "GET", f"{B}/{uuid.uuid4()}", token=ops, expect=404)
    rec.call("audit-clinical-view", "GET", f"{ADMIN}/audit", token=boss, params={
        "entity_type": "booking", "action": "booking.clinical_view", "limit": 1})
    rec.call("booking-candidates", "GET", f"{B}/{unmatched['id']}/candidates", token=ops)

    # --- re-dispatch -------------------------------------------------------------------------------------
    rec.call("redispatch-no-reason", "POST", f"{B}/{unmatched['id']}/redispatch", token=ops, expect=422, json_body={})
    rec.call("redispatch-held", "POST", f"{B}/{held['id']}/redispatch", token=ops, expect=409,
             json_body={"reason": "Try again"})
    rec.call("redispatch", "POST", f"{B}/{unmatched['id']}/redispatch", token=ops,
             json_body={"reason": "Nurses are online again", "radius_km": 25})

    # --- assign / reassign -----------------------------------------------------------------------------------
    rec.call("assign-offer", "POST", f"{B}/{to_offer['id']}/assign", token=ops,
             json_body={"caregiver_id": cg1, "reason": "Known to the patient"},
             note="An offer: the caregiver still has to accept in the app. The booking stays pending.")
    rec.call("assign-unapproved", "POST", f"{B}/{to_offer['id']}/assign", token=ops, expect=409,
             json_body={"caregiver_id": cg_unapproved, "reason": "Trying"})
    rec.call("assign-force-as-ops", "POST", f"{B}/{to_force['id']}/assign", token=ops, expect=403,
             json_body={"caregiver_id": cg2, "reason": "Patient is waiting", "force": True})
    rec.call("assign-force", "POST", f"{B}/{to_force['id']}/assign", token=boss,
             json_body={"caregiver_id": cg2, "reason": "Patient is waiting", "force": True},
             note="Super Admin only: no accept step. The booking is accepted and the caregiver is told.")
    rec.call("reassign-same-caregiver", "POST", f"{B}/{to_reassign['id']}/reassign", token=ops, expect=409,
             json_body={"caregiver_id": cg1, "reason": "Same one"})
    rec.call("reassign", "POST", f"{B}/{to_reassign['id']}/reassign", token=ops,
             json_body={"caregiver_id": cg2, "reason": "First caregiver is unwell"})
    rec.call("assign-on-accepted-booking", "POST", f"{B}/{to_reassign['id']}/assign", token=ops, expect=409,
             json_body={"caregiver_id": cg_far, "reason": "Wrong endpoint"},
             note="/assign never turns into a reassignment: an accepted booking is a 409.")

    # --- cancel ---------------------------------------------------------------------------------------------------
    rec.call("cancel-partial-no-amount", "POST", f"{B}/{to_cancel['id']}/cancel", token=ops, expect=422,
             json_body={"reason_code": "patient_request", "reason": "Patient called", "refund": "partial"})
    rec.call("cancel", "POST", f"{B}/{to_cancel['id']}/cancel", token=ops, json_body={
        "reason_code": "patient_request", "reason": "Patient called to cancel", "refund": "full"},
        note="No money moves. refund_required is set for the refund queue; a WhatsApp booker is told a refund is coming.")
    rec.call("cancel-again", "POST", f"{B}/{to_cancel['id']}/cancel", token=ops, expect=409,
             json_body={"reason_code": "patient_request", "reason": "Again", "refund": "none"})
    rec.call("cancel-unpaid-with-refund", "POST", f"{B}/{unpaid['id']}/cancel", token=ops, expect=422,
             json_body={"reason_code": "duplicate", "reason": "Duplicate booking", "refund": "full"})
    rec.call("cancel-unpaid", "POST", f"{B}/{unpaid['id']}/cancel", token=ops, json_body={
        "reason_code": "duplicate", "reason": "Duplicate booking", "refund": "none"})

    # --- confirm address ----------------------------------------------------------------------------------------------
    rec.call("confirm-address-outside-nigeria", "POST", f"{B}/{held['id']}/confirm-address", token=ops, expect=422,
             json_body={"reason": "Typo", "latitude": 51.5, "longitude": -0.12})
    rec.call("confirm-address", "POST", f"{B}/{held['id']}/confirm-address", token=ops, json_body={
        "reason": "Called the booker and confirmed the street", "latitude": LAT, "longitude": LON,
        "address": "14 Placeholder Close, Lekki"},
        note="Clears the hold and starts dispatch in the same call (wave 1 goes to nearby caregivers).")
    rec.call("confirm-address-again", "POST", f"{B}/{held['id']}/confirm-address", token=ops, expect=409,
             json_body={"reason": "Again", "latitude": LAT, "longitude": LON})
    rec.call("booking-detail-after-confirm", "GET", f"{B}/{held['id']}", token=ops,
             note="The timeline now shows the dispatch wave, the offers and the admin action.")

    # --- no-show and status correction --------------------------------------------------------------------------------------
    rec.call("no-show", "POST", f"{B}/{late['id']}/no-show", token=ops, json_body={"reason": "Caregiver not reachable"})
    rec.call("no-show-again", "POST", f"{B}/{late['id']}/no-show", token=ops, expect=409,
             json_body={"reason": "Again"})
    rec.call("correct-status-as-ops", "POST", f"{B}/{running['id']}/correct-status", token=ops, expect=403,
             json_body={"status": "completed", "reason": "Forgot to check out"})
    rec.call("correct-status", "POST", f"{B}/{running['id']}/correct-status", token=boss,
             json_body={"status": "completed", "reason": "Caregiver forgot to check out"})
    rec.call("correct-status-again", "POST", f"{B}/{running['id']}/correct-status", token=boss, expect=409,
             json_body={"status": "completed", "reason": "Again"})
    rec.call("audit-booking-actions", "GET", f"{ADMIN}/audit", token=boss, params={"entity_type": "booking", "limit": 5},
             note="Every action above wrote one entry, newest first.")


def run(args) -> None:
    out = Path(args.out)
    env = read_env(args.env_file)
    rec = AdminRecorder(args.base_url, out)
    db = DB(args.db_url)
    tag = uuid.uuid4().hex[:6]
    if args.section == "bookings":
        # Replace only the A2 captures: everything numbered from the section's first file is deleted and made
        # again after the earlier ones, which stay as they are.
        index = json.loads((out / "000-index.json").read_text())
        first = index.get("sections", {}).get("bookings", len(index["captures"]) + 1)
        for stale in out.glob("*.json"):
            if stale.name != "000-index.json" and int(stale.name[:3]) >= first:
                stale.unlink()
        rec.index = [c for c in index["captures"] if int(c["file"][:3]) < first]
        rec.n = first - 1
        index.setdefault("sections", {})["bookings"] = first
        bookings_ops(rec, db, env, tag)
        index["captures"] = rec.index
        (out / "000-index.json").write_text(json.dumps(index, indent=2) + "\n")
        print(f"wrote {len(rec.index)} captures to {out}")
        return
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    admins = Admins(db, env, tag)
    seeded = "SEEDED: the first Super Admin is inserted directly (production uses scripts.create_super_admin). MFA is already enrolled."

    # --- 1. sign in, the happy path and its errors --------------------------------------------------
    boss_email = admins.seed("boss", "super_admin", "Placeholder Super Admin")
    rec.call("login-wrong-password", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": boss_email, "password": "wrong-password-123"})
    rec.call("login-unknown-email", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": "nobody@example.com", "password": "wrong-password-123"})
    rec.call("login-invalid-email", "POST", f"{ADMIN}/auth/login", expect=422,
             json_body={"email": "not-an-email", "password": "x"})
    step1 = rec.call("login", "POST", f"{ADMIN}/auth/login", note=seeded,
                     json_body={"email": boss_email, "password": PLACEHOLDER_PASSWORD}).json()
    rec.call("mfa-verify-wrong-code", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             json_body={"mfa_token": step1["mfa_token"], "code": "000000"})
    rec.call("mfa-verify-bad-token", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             json_body={"mfa_token": "not-a-token", "code": "000000"})
    code = admins.code(boss_email)
    boss = rec.call("mfa-verify", "POST", f"{ADMIN}/auth/mfa/verify",
                    json_body={"mfa_token": step1["mfa_token"], "code": code}).json()
    tb = boss["access_token"]

    # the same code again, with a brand-new password step: refused (replay inside its 30-second step)
    again = rec.call("login-again", "POST", f"{ADMIN}/auth/login", note="A second sign-in right away.",
                     json_body={"email": boss_email, "password": PLACEHOLDER_PASSWORD}).json()
    rec.call("mfa-verify-replay", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             note="The 6-digit code from the previous call, submitted again inside the same 30-second step.",
             json_body={"mfa_token": again["mfa_token"], "code": code})

    rec.call("me", "GET", f"{ADMIN}/me", token=tb)
    rec.call("me-no-token", "GET", f"{ADMIN}/me", expect=401)
    rec.call("me-refresh-token-as-bearer", "GET", f"{ADMIN}/me", token=boss["refresh_token"], expect=401)
    rec.call("me-garbage-token", "GET", f"{ADMIN}/me", token="not-a-token", expect=401)

    # --- 2. admin and app tokens never cross ----------------------------------------------------------
    rec.quiet = True
    patient_email = f"patient-{tag}@example.com"
    rec.call("p-register", "POST", f"{API}/auth/register", json_body={
        "email": patient_email, "password": PLACEHOLDER_PASSWORD, "full_name": "Placeholder Patient",
        "phone_number": f"+2340000{int(tag, 16) % 1000:03d}001", "user_type": "patient"})
    (otp,), = db.run("SELECT verification_code FROM users WHERE email = %s", (patient_email,))
    rec.call("p-verify", "POST", f"{API}/auth/verify-email", json_body={"email": patient_email, "code": otp})
    app_token = rec.call("p-login", "POST", f"{API}/auth/login/mobile", json_body={
        "email_or_phone": patient_email, "password": PLACEHOLDER_PASSWORD}).json()["access_token"]
    rec.quiet = False
    rec.call("admin-route-with-app-token", "GET", f"{ADMIN}/me", token=app_token, expect=401,
             note="A patient's access token on an admin route.")
    rec.call("app-route-with-admin-token", "GET", f"{API}/auth/me", token=tb, expect=401,
             note="An admin's access token on an app route.")

    # --- 3. refresh rotation and reuse detection ----------------------------------------------------------
    wait_for_new_rate_window()  # keep each section inside the per-IP limit (30 auth calls a minute)
    rotated = rec.call("refresh", "POST", f"{ADMIN}/auth/refresh",
                       json_body={"refresh_token": boss["refresh_token"]}).json()
    rec.call("me-after-refresh", "GET", f"{ADMIN}/me", token=rotated["access_token"])
    rec.call("refresh-reuse", "POST", f"{ADMIN}/auth/refresh", expect=401,
             note="The first refresh token again, after it was rotated: treated as theft.",
             json_body={"refresh_token": boss["refresh_token"]})
    rec.call("refresh-after-reuse-sibling-token", "POST", f"{ADMIN}/auth/refresh", expect=401,
             note="The NEW refresh token from the rotation is dead too: every session of the admin was revoked.",
             json_body={"refresh_token": rotated["refresh_token"]})
    rec.call("me-after-reuse", "GET", f"{ADMIN}/me", token=rotated["access_token"], expect=401,
             note="The access token issued by the rotation stops working at once, not after 15 minutes.")
    rec.call("refresh-unknown-token", "POST", f"{ADMIN}/auth/refresh", expect=401,
             json_body={"refresh_token": "never-issued"})

    boss = login_and_verify(rec, admins, "boss-again", boss_email)
    tb = boss["access_token"]

    # --- 4. logout -----------------------------------------------------------------------------------------
    second = login_and_verify(rec, admins, "boss-second-device", boss_email)
    rec.call("logout", "POST", f"{ADMIN}/auth/logout", json_body={"refresh_token": second["refresh_token"]}, expect=204)
    rec.call("me-after-logout", "GET", f"{ADMIN}/me", token=second["access_token"], expect=401)
    rec.call("me-other-session-after-logout", "GET", f"{ADMIN}/me", token=tb,
             note="Logging out one session does not touch the admin's other sessions.")

    # --- 5. inviting an admin: invited -> active, MFA enrolment forced -------------------------------------------
    wait_for_new_rate_window()
    invite_email = admins.email("verifier")
    invite = rec.call("invite", "POST", f"{ADMIN}/admins", token=tb, expect=201, json_body={
        "email": invite_email, "full_name": "Placeholder Verifier", "roles": ["verification"]}).json()
    rec.call("invite-duplicate", "POST", f"{ADMIN}/admins", token=tb, expect=409, json_body={
        "email": invite_email, "full_name": "Placeholder Verifier", "roles": ["verification"]})
    rec.call("invite-unknown-role", "POST", f"{ADMIN}/admins", token=tb, expect=422, json_body={
        "email": admins.email("nobody"), "full_name": "Placeholder Nobody", "roles": ["wizard"]})
    rec.call("invite-no-roles", "POST", f"{ADMIN}/admins", token=tb, expect=422, json_body={
        "email": admins.email("nobody"), "full_name": "Placeholder Nobody", "roles": []})
    rec.call("login-before-accepting-invite", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": invite_email, "password": STRONG_PASSWORD})
    rec.call("invite-accept-weak-password", "POST", f"{ADMIN}/auth/invite/accept", expect=422,
             json_body={"invite_token": invite["invite_token"], "password": "short"})
    rec.call("invite-accept-password-contains-email", "POST", f"{ADMIN}/auth/invite/accept", expect=422,
             json_body={"invite_token": invite["invite_token"], "password": f"verifier-{tag}-Aa1!x"})
    rec.call("invite-accept", "POST", f"{ADMIN}/auth/invite/accept",
             json_body={"invite_token": invite["invite_token"], "password": STRONG_PASSWORD})
    rec.call("invite-accept-again", "POST", f"{ADMIN}/auth/invite/accept", expect=400,
             json_body={"invite_token": invite["invite_token"], "password": STRONG_PASSWORD})
    enrol = rec.call("login-first-time", "POST", f"{ADMIN}/auth/login", note="First sign-in: MFA is not enrolled yet.",
                     json_body={"email": invite_email, "password": STRONG_PASSWORD}).json()
    admins.secrets[invite_email] = enrol["secret"]
    verifier = rec.call("mfa-verify-enrolment", "POST", f"{ADMIN}/auth/mfa/verify", json_body={
        "mfa_token": enrol["mfa_token"], "code": admins.code(invite_email)}).json()
    tv = verifier["access_token"]
    rec.call("login-after-enrolment", "POST", f"{ADMIN}/auth/login",
             json_body={"email": invite_email, "password": STRONG_PASSWORD})

    # an invite that expires (simulated), on a second invitee
    stale_email = admins.email("stale")
    stale = rec.call("invite-second", "POST", f"{ADMIN}/admins", token=tb, expect=201, json_body={
        "email": stale_email, "full_name": "Placeholder Stale", "roles": ["support"]}).json()
    db.run("UPDATE admin_users SET invite_expires_at = now() - interval '1 minute' WHERE email = %s", (stale_email,))
    rec.call("invite-accept-expired", "POST", f"{ADMIN}/auth/invite/accept", expect=400,
             note="db-simulated: the invite's expiry was moved into the past (the real window is 48 hours).",
             json_body={"invite_token": stale["invite_token"], "password": STRONG_PASSWORD})

    # --- 6. permissions ------------------------------------------------------------------------------------------
    rec.call("verifier-me", "GET", f"{ADMIN}/me", token=tv)
    rec.call("forbidden-admins-list", "GET", f"{ADMIN}/admins", token=tv, expect=403,
             note="A Verification admin on an admin-management route.")
    rec.call("forbidden-audit", "GET", f"{ADMIN}/audit", token=tv, expect=403)
    rec.call("caregiver-queue-as-verifier", "GET", f"{ADMIN}/caregivers", token=tv,
             note="A route the Verification role may use.")
    analyst_email = admins.seed("analyst", "read_only_analyst", "Placeholder Analyst")
    ta = login_and_verify(rec, admins, "analyst", analyst_email)["access_token"]
    rec.call("caregiver-queue-as-analyst", "GET", f"{ADMIN}/caregivers", token=ta, expect=403,
             note=f"SEEDED: {analyst_email} is a Read-only Analyst, inserted directly.")
    rec.call("caregiver-approve-no-token", "POST", f"{ADMIN}/caregivers/{uuid.uuid4()}/approve", expect=401)

    # --- 7. managing admins ----------------------------------------------------------------------------------------------
    rec.call("admins-list", "GET", f"{ADMIN}/admins", token=tb)
    rec.call("admin-update-roles", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb,
             json_body={"roles": ["verification", "support"]})
    rec.call("admin-update-invalid-status", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb, expect=422,
             json_body={"status": "invited"})
    rec.call("admin-update-unknown", "PATCH", f"{ADMIN}/admins/{uuid.uuid4()}", token=tb, expect=404,
             json_body={"status": "disabled"})
    rec.call("last-super-admin-demote", "PATCH", f"{ADMIN}/admins/{boss['admin']['id']}", token=tb, expect=409,
             json_body={"roles": ["operations"]})
    rec.call("disable-self", "PATCH", f"{ADMIN}/admins/{boss['admin']['id']}", token=tb, expect=409,
             json_body={"status": "disabled"})
    rec.call("admin-disable", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb, json_body={"status": "disabled"})
    rec.call("disabled-admin-token", "GET", f"{ADMIN}/me", token=tv, expect=401,
             note="The disabled admin's access token stops working immediately.")
    rec.call("disabled-admin-login", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": invite_email, "password": STRONG_PASSWORD})
    rec.call("admin-reactivate", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb, json_body={"status": "active"})
    rec.call("admin-activate-never-accepted", "PATCH", f"{ADMIN}/admins/{stale['id']}", token=tb, expect=409,
             json_body={"status": "active"})
    rec.call("reset-mfa", "POST", f"{ADMIN}/admins/{invite['id']}/reset-mfa", token=tb)
    reenrol = rec.call("login-after-mfa-reset", "POST", f"{ADMIN}/auth/login",
                       json_body={"email": invite_email, "password": STRONG_PASSWORD}).json()
    admins.secrets[invite_email] = reenrol["secret"]
    rec.call("reset-mfa-unknown", "POST", f"{ADMIN}/admins/{uuid.uuid4()}/reset-mfa", token=tb, expect=404)

    # --- 8. the audit log -----------------------------------------------------------------------------------------------------
    rec.call("audit", "GET", f"{ADMIN}/audit", token=tb, params={"limit": 3},
             note="Newest first; the console's audit viewer is this call with filters.")
    rec.call("audit-filtered", "GET", f"{ADMIN}/audit", token=tb, params={
        "entity_type": "admin_user", "action": "admin.update", "limit": 2})
    rec.call("audit-bad-limit", "GET", f"{ADMIN}/audit", token=tb, expect=422, params={"limit": 0})

    # --- 9. idle timeout (simulated) --------------------------------------------------------------------------------------------
    idle = login_and_verify(rec, admins, "idle", boss_email)
    db.run("UPDATE admin_refresh_tokens SET expires_at = now() - interval '1 minute' WHERE token_hash = encode(sha256(%s::bytea), 'hex')",
           (idle["refresh_token"],))
    rec.call("refresh-after-idle-timeout", "POST", f"{ADMIN}/auth/refresh", expect=401,
             note="db-simulated: the refresh token's expiry was moved into the past (the real idle window is 30 minutes).",
             json_body={"refresh_token": idle["refresh_token"]})

    # --- 10. password throttle (per email + IP, never a hard lock) -----------------------------------------------------------------
    victim = admins.seed("throttled", "support", "Placeholder Throttled")
    wait_for_new_rate_window()
    free = 5  # ADMIN_PASSWORD_FREE_ATTEMPTS default
    for who, email in (("known", victim), ("unknown", admins.email("nobody-at-all"))):
        rec.quiet = True
        for _ in range(free - 1):
            rec.call("throttle-fail", "POST", f"{ADMIN}/auth/login", expect=401,
                     json_body={"email": email, "password": "wrong-password-123"})
        rec.quiet = False
        rec.call(f"login-failure-{free}-{who}-email", "POST", f"{ADMIN}/auth/login", expect=401,
                 note=f"The {free}th wrong password for a {who} email: still 401.",
                 json_body={"email": email, "password": "wrong-password-123"})
        rec.call(f"login-throttled-{who}-email", "POST", f"{ADMIN}/auth/login", expect=429,
                 note=f"Attempt {free + 1}: 429 with Retry-After. Identical for known and unknown emails.",
                 json_body={"email": email, "password": "wrong-password-123"})
    rec.call("login-throttled-correct-password", "POST", f"{ADMIN}/auth/login", expect=429,
             note="The right password is refused too while throttled (the answer must not reveal it was right).",
             json_body={"email": victim, "password": PLACEHOLDER_PASSWORD})

    # --- 11. MFA lock (password already proven, so this one is a hard lock) -------------------------------------------------------
    locked = admins.seed("lockme", "support", "Placeholder Locked")
    step1 = rec.call("lock-login", "POST", f"{ADMIN}/auth/login",
                     json_body={"email": locked, "password": PLACEHOLDER_PASSWORD}).json()
    rec.quiet = True
    for _ in range(9):
        rec.call("lock-fail", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
                 json_body={"mfa_token": step1["mfa_token"], "code": "000000"})
    rec.quiet = False
    rec.call("mfa-failure-10", "POST", f"{ADMIN}/auth/mfa/verify", expect=401, note="The 10th wrong code.",
             json_body={"mfa_token": step1["mfa_token"], "code": "000000"})
    rec.call("mfa-locked", "POST", f"{ADMIN}/auth/mfa/verify", expect=423,
             note="The 11th attempt: the account is locked (15 minutes the first time, then 1 hour, then 24 hours).",
             json_body={"mfa_token": step1["mfa_token"], "code": "000000"})
    rec.call("login-while-mfa-locked", "POST", f"{ADMIN}/auth/login", expect=423,
             note="Only someone with the right password sees the lock.",
             json_body={"email": locked, "password": PLACEHOLDER_PASSWORD})
    rec.call("login-wrong-password-while-mfa-locked", "POST", f"{ADMIN}/auth/login", expect=401,
             note="A wrong password cannot tell the account is locked.",
             json_body={"email": locked, "password": "wrong-password-123"})

    # --- 12. mfa_token is single use ------------------------------------------------------------------------------------------------
    once_email = admins.seed("once", "support", "Placeholder Once")
    once = rec.call("single-use-login", "POST", f"{ADMIN}/auth/login",
                    json_body={"email": once_email, "password": PLACEHOLDER_PASSWORD}).json()
    rec.call("single-use-verify", "POST", f"{ADMIN}/auth/mfa/verify",
             json_body={"mfa_token": once["mfa_token"], "code": admins.code(once_email)})
    rec.call("single-use-verify-again", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             note="The same mfa_token with a fresh valid code: refused. Sign in again from the password step.",
             json_body={"mfa_token": once["mfa_token"], "code": admins.code(once_email)})

    # --- 13. per-IP rate limit (login and verify; refresh is not in it) -------------------------------------------------------
    wait_for_new_rate_window()
    late = login_and_verify(rec, admins, "late", boss_email)
    wait_for_new_rate_window()
    rec.quiet = True
    limit = int(env.get("ADMIN_AUTH_IP_LIMIT", 30))
    for _ in range(limit):
        rec.call("rate-fill", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
                 json_body={"mfa_token": "never-issued", "code": "000000"})
    rec.quiet = False
    rec.call("rate-limited", "POST", f"{ADMIN}/auth/mfa/verify", expect=429,
             note=f"Call number {limit + 1} from one IP inside one 60-second window.",
             json_body={"mfa_token": "never-issued", "code": "000000"})
    rec.call("login-rate-limited", "POST", f"{ADMIN}/auth/login", expect=429,
             json_body={"email": boss_email, "password": PLACEHOLDER_PASSWORD})
    rec.call("refresh-while-ip-limited", "POST", f"{ADMIN}/auth/refresh",
             note="Refresh is not part of the per-IP limit: it still works while login and verify are limited.",
             json_body={"refresh_token": late["refresh_token"]})

    first_bookings = rec.n + 1
    bookings_ops(rec, db, env, tag)

    (out / "000-index.json").write_text(json.dumps({
        "generated_by": "scripts/capture_admin_flow.py", "run_tag": tag, "sections": {"bookings": first_bookings},
        "captures": rec.index}, indent=2) + "\n")
    print(f"wrote {len(rec.index)} captures to {out}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base-url", default="http://127.0.0.1:8000")
    p.add_argument("--db-url", default="postgresql://oakly:oakly@127.0.0.1:5432/oakly")
    p.add_argument("--env-file", required=True, help="the env file the stack was started with (for the Fernet key)")
    p.add_argument("--out", default="docs/fe-captures/admin")
    p.add_argument("--section", choices=["all", "bookings"], default="all",
                   help="'bookings' re-captures only the A2 section and appends it to the existing captures")
    run(p.parse_args())


if __name__ == "__main__":
    main()
