"""Capture the admin auth and admin-management flow against a RUNNING Oakly stack and write every
request/response to docs/fe-captures/admin/*.json. docs/fe-integration-guide-admin.md is copied from
these files, never from the schemas.

    OAKLY_ENV_FILE_PATH=/path/to/temp.env docker compose -p oakly-a0 up --build -d db api
    poetry run python -m scripts.capture_admin_flow --env-file /path/to/temp.env
    docker compose -p oakly-a0 down -v

What is real and what is not
- Every API call is a real HTTP call to the running API (default http://127.0.0.1:8000).
- Seeded directly in the database: the first Super Admin and one admin per role used below (the only API
  that creates an admin needs an existing admin; production uses `python -m scripts.create_super_admin`).
  Their TOTP secrets are generated by this script, so the script can compute the 6-digit codes. Each seed
  is labelled in the captures.
- Two shortcuts are simulated in the database and labelled "db-simulated": the 30-minute idle timeout
  (the refresh token's expiry is moved into the past) and the 48-hour invite expiry.
- Invite delivery is not exercised: the API returns the invite token, and this script uses it directly.

Everything created here uses placeholder data (example.com emails, fake names). Secrets are replaced in
the files: JWTs, refresh/invite tokens, TOTP secrets and codes, passwords.
"""

import argparse
import json
import re
import shutil
import time
import uuid
from pathlib import Path
from typing import Any, Dict, Optional

import pyotp
from cryptography.fernet import Fernet

from scripts.capture_caregiver_flow import (
    DB,
    PLACEHOLDER_PASSWORD,
    Recorder,
    hash_password,
    read_env,
)

API = "/api/v1"
ADMIN = f"{API}/admin"
STRONG_PASSWORD = "Placeholder-Admin-Pass-9!"
WINDOW_SECONDS = 60  # ADMIN_AUTH_IP_WINDOW_SECONDS default
SECRET_PARAM = re.compile(r"secret=[A-Z2-7]+")


class AdminRecorder(Recorder):
    """Recorder that also blanks the secrets the base redaction does not know about."""

    def save(self, label: str, doc: Dict[str, Any]) -> None:
        super().save(label, scrub(doc))


def scrub(value: Any, key: Optional[str] = None) -> Any:
    if isinstance(value, dict):
        out = {}
        for k, v in value.items():
            if k == "code" and isinstance(v, str) and v != "000000" and v.isdigit() and len(v) == 6:
                out[k] = "<TOTP_CODE>"
            else:
                out[k] = scrub(v, k)
        return out
    if isinstance(value, list):
        return [scrub(v) for v in value]
    if isinstance(value, str):
        if key == "mfa_token":
            return "<MFA_TOKEN_JWT>"
        if key == "refresh_token" and not value.startswith("<"):
            return "<REFRESH_TOKEN>"
        if key == "invite_token" and not value.startswith("<"):
            return "<INVITE_TOKEN>"
        if key == "secret":
            return "<TOTP_SECRET>"
        if key == "otpauth_uri":
            return SECRET_PARAM.sub("secret=<TOTP_SECRET>", value)
    return value


class Admins:
    """Seeds admin accounts straight into the database and remembers their TOTP secrets."""

    def __init__(self, db: DB, env: Dict[str, str], tag: str):
        self.db, self.tag = db, tag
        self.fernet = Fernet(env["VITALS_ENCRYPTION_KEY"].split(",")[0].strip().encode())
        self.secrets: Dict[str, str] = {}
        self.last_step: Dict[str, int] = {}

    def code(self, email: str) -> str:
        """The current 6-digit code. A code can be used once per 30-second step (replay protection), so a
        second sign-in in the same step waits for the next one, exactly as a person would have to."""
        step = int(time.time() // 30)
        if self.last_step.get(email) == step:
            time.sleep(30 - (time.time() % 30) + 0.5)
            step = int(time.time() // 30)
        self.last_step[email] = step
        return pyotp.TOTP(self.secrets[email]).now()

    def email(self, who: str) -> str:
        return f"{who}-{self.tag}@example.com"

    def seed(self, who: str, role: str, full_name: str) -> str:
        email, secret, admin_id = self.email(who), pyotp.random_base32(), str(uuid.uuid4())
        self.db.run(
            "INSERT INTO admin_users (id, email, full_name, password_hash, status, mfa_secret_enc, mfa_enabled,"
            " failed_logins, created_at, updated_at) VALUES (%s,%s,%s,%s,'active',%s,true,0,now(),now())",
            (admin_id, email, full_name, hash_password(PLACEHOLDER_PASSWORD),
             self.fernet.encrypt(secret.encode()).decode()))
        self.db.run("INSERT INTO admin_user_roles (admin_user_id, role_id) SELECT %s, id FROM admin_roles WHERE key = %s",
                    (admin_id, role))
        self.secrets[email] = secret
        return email


def wait_for_new_rate_window() -> None:
    """The per-IP counters are fixed 60-second windows; start a burst of calls right after a boundary."""
    time.sleep(WINDOW_SECONDS - (time.time() % WINDOW_SECONDS) + 1.5)


def login_and_verify(rec: Recorder, admins: Admins, label: str, email: str, password: str = PLACEHOLDER_PASSWORD,
                     capture: bool = False) -> Dict[str, Any]:
    """Sign in through the real endpoints. Quiet unless ``capture``."""
    saved = rec.quiet
    rec.quiet = saved or not capture
    step1 = rec.call(f"{label}-login", "POST", f"{ADMIN}/auth/login",
                     json_body={"email": email, "password": password}).json()
    code = admins.code(email)
    body = rec.call(f"{label}-mfa-verify", "POST", f"{ADMIN}/auth/mfa/verify",
                    json_body={"mfa_token": step1["mfa_token"], "code": code}).json()
    rec.quiet = saved
    return body


def run(args) -> None:
    out = Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    env = read_env(args.env_file)
    rec = AdminRecorder(args.base_url, out)
    db = DB(args.db_url)
    tag = uuid.uuid4().hex[:6]
    admins = Admins(db, env, tag)
    seeded = "SEEDED: the first Super Admin is inserted directly (production uses scripts.create_super_admin). MFA is already enrolled."

    # --- 1. sign in, the happy path and its errors --------------------------------------------------
    boss_email = admins.seed("boss", "super_admin", "Placeholder Super Admin")
    rec.call("login-wrong-password", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": boss_email, "password": "wrong-password-123"})
    rec.call("login-unknown-email", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": "nobody@example.com", "password": "wrong-password-123"})
    rec.call("login-invalid-email", "POST", f"{ADMIN}/auth/login", expect=422,
             json_body={"email": "not-an-email", "password": "x"})
    step1 = rec.call("login", "POST", f"{ADMIN}/auth/login", note=seeded,
                     json_body={"email": boss_email, "password": PLACEHOLDER_PASSWORD}).json()
    rec.call("mfa-verify-wrong-code", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             json_body={"mfa_token": step1["mfa_token"], "code": "000000"})
    rec.call("mfa-verify-bad-token", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             json_body={"mfa_token": "not-a-token", "code": "000000"})
    code = admins.code(boss_email)
    boss = rec.call("mfa-verify", "POST", f"{ADMIN}/auth/mfa/verify",
                    json_body={"mfa_token": step1["mfa_token"], "code": code}).json()
    tb = boss["access_token"]

    # the same code again, with a brand-new password step: refused (replay inside its 30-second step)
    again = rec.call("login-again", "POST", f"{ADMIN}/auth/login", note="A second sign-in right away.",
                     json_body={"email": boss_email, "password": PLACEHOLDER_PASSWORD}).json()
    rec.call("mfa-verify-replay", "POST", f"{ADMIN}/auth/mfa/verify", expect=401,
             note="The 6-digit code from the previous call, submitted again inside the same 30-second step.",
             json_body={"mfa_token": again["mfa_token"], "code": code})

    rec.call("me", "GET", f"{ADMIN}/me", token=tb)
    rec.call("me-no-token", "GET", f"{ADMIN}/me", expect=401)
    rec.call("me-refresh-token-as-bearer", "GET", f"{ADMIN}/me", token=boss["refresh_token"], expect=401)
    rec.call("me-garbage-token", "GET", f"{ADMIN}/me", token="not-a-token", expect=401)

    # --- 2. admin and app tokens never cross ----------------------------------------------------------
    rec.quiet = True
    patient_email = f"patient-{tag}@example.com"
    rec.call("p-register", "POST", f"{API}/auth/register", json_body={
        "email": patient_email, "password": PLACEHOLDER_PASSWORD, "full_name": "Placeholder Patient",
        "phone_number": f"+2340000{int(tag, 16) % 1000:03d}001", "user_type": "patient"})
    (otp,), = db.run("SELECT verification_code FROM users WHERE email = %s", (patient_email,))
    rec.call("p-verify", "POST", f"{API}/auth/verify-email", json_body={"email": patient_email, "code": otp})
    app_token = rec.call("p-login", "POST", f"{API}/auth/login/mobile", json_body={
        "email_or_phone": patient_email, "password": PLACEHOLDER_PASSWORD}).json()["access_token"]
    rec.quiet = False
    rec.call("admin-route-with-app-token", "GET", f"{ADMIN}/me", token=app_token, expect=401,
             note="A patient's access token on an admin route.")
    rec.call("app-route-with-admin-token", "GET", f"{API}/auth/me", token=tb, expect=401,
             note="An admin's access token on an app route.")

    # --- 3. refresh rotation and reuse detection ----------------------------------------------------------
    wait_for_new_rate_window()  # keep each section inside the per-IP limit (30 auth calls a minute)
    rotated = rec.call("refresh", "POST", f"{ADMIN}/auth/refresh",
                       json_body={"refresh_token": boss["refresh_token"]}).json()
    rec.call("me-after-refresh", "GET", f"{ADMIN}/me", token=rotated["access_token"])
    rec.call("refresh-reuse", "POST", f"{ADMIN}/auth/refresh", expect=401,
             note="The first refresh token again, after it was rotated: treated as theft.",
             json_body={"refresh_token": boss["refresh_token"]})
    rec.call("refresh-after-reuse-sibling-token", "POST", f"{ADMIN}/auth/refresh", expect=401,
             note="The NEW refresh token from the rotation is dead too: every session of the admin was revoked.",
             json_body={"refresh_token": rotated["refresh_token"]})
    rec.call("me-after-reuse", "GET", f"{ADMIN}/me", token=rotated["access_token"], expect=401,
             note="The access token issued by the rotation stops working at once, not after 15 minutes.")
    rec.call("refresh-unknown-token", "POST", f"{ADMIN}/auth/refresh", expect=401,
             json_body={"refresh_token": "never-issued"})

    boss = login_and_verify(rec, admins, "boss-again", boss_email)
    tb = boss["access_token"]

    # --- 4. logout -----------------------------------------------------------------------------------------
    second = login_and_verify(rec, admins, "boss-second-device", boss_email)
    rec.call("logout", "POST", f"{ADMIN}/auth/logout", json_body={"refresh_token": second["refresh_token"]}, expect=204)
    rec.call("me-after-logout", "GET", f"{ADMIN}/me", token=second["access_token"], expect=401)
    rec.call("me-other-session-after-logout", "GET", f"{ADMIN}/me", token=tb,
             note="Logging out one session does not touch the admin's other sessions.")

    # --- 5. inviting an admin: invited -> active, MFA enrolment forced -------------------------------------------
    wait_for_new_rate_window()
    invite_email = admins.email("verifier")
    invite = rec.call("invite", "POST", f"{ADMIN}/admins", token=tb, expect=201, json_body={
        "email": invite_email, "full_name": "Placeholder Verifier", "roles": ["verification"]}).json()
    rec.call("invite-duplicate", "POST", f"{ADMIN}/admins", token=tb, expect=409, json_body={
        "email": invite_email, "full_name": "Placeholder Verifier", "roles": ["verification"]})
    rec.call("invite-unknown-role", "POST", f"{ADMIN}/admins", token=tb, expect=422, json_body={
        "email": admins.email("nobody"), "full_name": "Placeholder Nobody", "roles": ["wizard"]})
    rec.call("invite-no-roles", "POST", f"{ADMIN}/admins", token=tb, expect=422, json_body={
        "email": admins.email("nobody"), "full_name": "Placeholder Nobody", "roles": []})
    rec.call("login-before-accepting-invite", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": invite_email, "password": STRONG_PASSWORD})
    rec.call("invite-accept-weak-password", "POST", f"{ADMIN}/auth/invite/accept", expect=422,
             json_body={"invite_token": invite["invite_token"], "password": "short"})
    rec.call("invite-accept-password-contains-email", "POST", f"{ADMIN}/auth/invite/accept", expect=422,
             json_body={"invite_token": invite["invite_token"], "password": f"verifier-{tag}-Aa1!x"})
    rec.call("invite-accept", "POST", f"{ADMIN}/auth/invite/accept",
             json_body={"invite_token": invite["invite_token"], "password": STRONG_PASSWORD})
    rec.call("invite-accept-again", "POST", f"{ADMIN}/auth/invite/accept", expect=400,
             json_body={"invite_token": invite["invite_token"], "password": STRONG_PASSWORD})
    enrol = rec.call("login-first-time", "POST", f"{ADMIN}/auth/login", note="First sign-in: MFA is not enrolled yet.",
                     json_body={"email": invite_email, "password": STRONG_PASSWORD}).json()
    admins.secrets[invite_email] = enrol["secret"]
    verifier = rec.call("mfa-verify-enrolment", "POST", f"{ADMIN}/auth/mfa/verify", json_body={
        "mfa_token": enrol["mfa_token"], "code": admins.code(invite_email)}).json()
    tv = verifier["access_token"]
    rec.call("login-after-enrolment", "POST", f"{ADMIN}/auth/login",
             json_body={"email": invite_email, "password": STRONG_PASSWORD})

    # an invite that expires (simulated), on a second invitee
    stale_email = admins.email("stale")
    stale = rec.call("invite-second", "POST", f"{ADMIN}/admins", token=tb, expect=201, json_body={
        "email": stale_email, "full_name": "Placeholder Stale", "roles": ["support"]}).json()
    db.run("UPDATE admin_users SET invite_expires_at = now() - interval '1 minute' WHERE email = %s", (stale_email,))
    rec.call("invite-accept-expired", "POST", f"{ADMIN}/auth/invite/accept", expect=400,
             note="db-simulated: the invite's expiry was moved into the past (the real window is 48 hours).",
             json_body={"invite_token": stale["invite_token"], "password": STRONG_PASSWORD})

    # --- 6. permissions ------------------------------------------------------------------------------------------
    rec.call("verifier-me", "GET", f"{ADMIN}/me", token=tv)
    rec.call("forbidden-admins-list", "GET", f"{ADMIN}/admins", token=tv, expect=403,
             note="A Verification admin on an admin-management route.")
    rec.call("forbidden-audit", "GET", f"{ADMIN}/audit", token=tv, expect=403)
    rec.call("caregiver-queue-as-verifier", "GET", f"{ADMIN}/caregivers", token=tv,
             note="A route the Verification role may use.")
    analyst_email = admins.seed("analyst", "read_only_analyst", "Placeholder Analyst")
    ta = login_and_verify(rec, admins, "analyst", analyst_email)["access_token"]
    rec.call("caregiver-queue-as-analyst", "GET", f"{ADMIN}/caregivers", token=ta, expect=403,
             note=f"SEEDED: {analyst_email} is a Read-only Analyst, inserted directly.")
    rec.call("caregiver-approve-no-token", "POST", f"{ADMIN}/caregivers/{uuid.uuid4()}/approve", expect=401)

    # --- 7. managing admins ----------------------------------------------------------------------------------------------
    rec.call("admins-list", "GET", f"{ADMIN}/admins", token=tb)
    rec.call("admin-update-roles", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb,
             json_body={"roles": ["verification", "support"]})
    rec.call("admin-update-invalid-status", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb, expect=422,
             json_body={"status": "invited"})
    rec.call("admin-update-unknown", "PATCH", f"{ADMIN}/admins/{uuid.uuid4()}", token=tb, expect=404,
             json_body={"status": "disabled"})
    rec.call("last-super-admin-demote", "PATCH", f"{ADMIN}/admins/{boss['admin']['id']}", token=tb, expect=409,
             json_body={"roles": ["operations"]})
    rec.call("disable-self", "PATCH", f"{ADMIN}/admins/{boss['admin']['id']}", token=tb, expect=409,
             json_body={"status": "disabled"})
    rec.call("admin-disable", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb, json_body={"status": "disabled"})
    rec.call("disabled-admin-token", "GET", f"{ADMIN}/me", token=tv, expect=401,
             note="The disabled admin's access token stops working immediately.")
    rec.call("disabled-admin-login", "POST", f"{ADMIN}/auth/login", expect=401,
             json_body={"email": invite_email, "password": STRONG_PASSWORD})
    rec.call("admin-reactivate", "PATCH", f"{ADMIN}/admins/{invite['id']}", token=tb, json_body={"status": "active"})
    rec.call("admin-activate-never-accepted", "PATCH", f"{ADMIN}/admins/{stale['id']}", token=tb, expect=409,
             json_body={"status": "active"})
    rec.call("reset-mfa", "POST", f"{ADMIN}/admins/{invite['id']}/reset-mfa", token=tb)
    reenrol = rec.call("login-after-mfa-reset", "POST", f"{ADMIN}/auth/login",
                       json_body={"email": invite_email, "password": STRONG_PASSWORD}).json()
    admins.secrets[invite_email] = reenrol["secret"]
    rec.call("reset-mfa-unknown", "POST", f"{ADMIN}/admins/{uuid.uuid4()}/reset-mfa", token=tb, expect=404)

    # --- 8. the audit log -----------------------------------------------------------------------------------------------------
    rec.call("audit", "GET", f"{ADMIN}/audit", token=tb, params={"limit": 3},
             note="Newest first; the console's audit viewer is this call with filters.")
    rec.call("audit-filtered", "GET", f"{ADMIN}/audit", token=tb, params={
        "entity_type": "admin_user", "action": "admin.update", "limit": 2})
    rec.call("audit-bad-limit", "GET", f"{ADMIN}/audit", token=tb, expect=422, params={"limit": 0})

    # --- 9. idle timeout (simulated) --------------------------------------------------------------------------------------------
    idle = login_and_verify(rec, admins, "idle", boss_email)
    db.run("UPDATE admin_refresh_tokens SET expires_at = now() - interval '1 minute' WHERE token_hash = encode(sha256(%s::bytea), 'hex')",
           (idle["refresh_token"],))
    rec.call("refresh-after-idle-timeout", "POST", f"{ADMIN}/auth/refresh", expect=401,
             note="db-simulated: the refresh token's expiry was moved into the past (the real idle window is 30 minutes).",
             json_body={"refresh_token": idle["refresh_token"]})

    # --- 10. lockout (own account, own rate-limit window) -----------------------------------------------------------------------------
    victim = admins.seed("lockme", "support", "Placeholder Locked")
    wait_for_new_rate_window()
    rec.quiet = True
    for _ in range(9):
        rec.call("lock-fail", "POST", f"{ADMIN}/auth/login", expect=401,
                 json_body={"email": victim, "password": "wrong-password-123"})
    rec.quiet = False
    rec.call("login-failure-10", "POST", f"{ADMIN}/auth/login", expect=401, note="The 10th wrong password.",
             json_body={"email": victim, "password": "wrong-password-123"})
    rec.call("login-locked", "POST", f"{ADMIN}/auth/login", expect=423, note="The 11th attempt: the account is locked.",
             json_body={"email": victim, "password": "wrong-password-123"})
    rec.call("login-locked-correct-password", "POST", f"{ADMIN}/auth/login", expect=423,
             note="The right password while locked is refused too.",
             json_body={"email": victim, "password": PLACEHOLDER_PASSWORD})

    # --- 11. per-IP rate limit ----------------------------------------------------------------------------------------------------------
    wait_for_new_rate_window()
    rec.quiet = True
    limit = int(env.get("ADMIN_AUTH_IP_LIMIT", 30))
    for _ in range(limit):
        rec.call("rate-fill", "POST", f"{ADMIN}/auth/refresh", expect=401, json_body={"refresh_token": "never-issued"})
    rec.quiet = False
    rec.call("rate-limited", "POST", f"{ADMIN}/auth/refresh", expect=429,
             note=f"Call number {limit + 1} from one IP inside one 60-second window.",
             json_body={"refresh_token": "never-issued"})

    (out / "000-index.json").write_text(json.dumps({
        "generated_by": "scripts/capture_admin_flow.py", "run_tag": tag, "captures": rec.index}, indent=2) + "\n")
    print(f"wrote {len(rec.index)} captures to {out}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base-url", default="http://127.0.0.1:8000")
    p.add_argument("--db-url", default="postgresql://oakly:oakly@127.0.0.1:5432/oakly")
    p.add_argument("--env-file", required=True, help="the env file the stack was started with (for the Fernet key)")
    p.add_argument("--out", default="docs/fe-captures/admin")
    run(p.parse_args())


if __name__ == "__main__":
    main()
